def sanitize_mermaid_code(mermaid_text: str) -> str:
    """
    Clean up Mermaid text to guarantee valid Mermaid.js diagram syntax.
    Strips code fences, leading tags, and ensures proper graph TD start.
    """
    cleaned = mermaid_text.strip()
    # Strip markdown code fences if present
    cleaned = re.sub(r"^```(?:mermaid)?\s*", "", cleaned, flags=re.MULTILINE)
    cleaned = re.sub(r"```\s*$", "", cleaned, flags=re.MULTILINE).strip()

    # Ensure it starts with graph TD or flowchart TD
    if not (cleaned.startswith("graph ") or cleaned.startswith("flowchart ")):
        cleaned = "graph TD\n" + cleaned

    return cleaned


def validate_python_syntax(code_str: str) -> Tuple[bool, Optional[str], Optional[int]]:
    """
    Validate Python code using the standard library AST parser.
    Returns (is_valid, error_description, error_line_no).
    """
    try:
        ast.parse(code_str)
        return True, None, None
    except SyntaxError as e:
        err_msg = f"SyntaxError at line {e.lineno}, col {e.offset}: {e.msg}\n--> {e.text or ''}"
        return False, err_msg, e.lineno
    except Exception as e:
        return False, f"Unexpected validation error: {str(e)}", None



def modernize_codebase(
    ingestion_result: IngestionResult,
    chunks: List[ASTChunk],
    api_key: Optional[str] = None,
    model_name: str = "gemini-2.5-pro",
) -> CodeModernizationOutput:
    """
    Modernize the ingested codebase using Gemini long-context structured generation.
    Enforces AST syntax validation and automatic 1-step self-correction retry.
    """
    key = api_key or os.getenv("GEMINI_API_KEY")
    if not key:
        # Return senior-dev mock if no API key provided
        return _mock_sample_modernization()

    xml_codebase = pack_to_xml(chunks)
    raw_code = "\n\n".join(
        f"--- File: {f.rel_path} ---\n{f.content}" for f in ingestion_result.files
    )

    prompt = _build_modernization_prompt(xml_codebase, raw_code)

    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=key)

        # Attempt structured generation with primary model
        response = client.models.generate_content(
            model=model_name,
            contents=prompt,
            config=types.GenerateContentConfig(
                response_mime_type="application/json",
                response_schema=CodeModernizationOutput,
                temperature=0.2,
            ),
        )

        parsed_data = json.loads(response.text)
        result = CodeModernizationOutput(**parsed_data)
        result.mermaid_flowchart = sanitize_mermaid_code(result.mermaid_flowchart)

    except Exception as e:
        # Fallback to gemini-2.5-flash if gemini-2.5-pro encountered an issue or rate limit
        if model_name != "gemini-2.5-flash":
            return modernize_codebase(
                ingestion_result=ingestion_result,
                chunks=chunks,
                api_key=key,
                model_name="gemini-2.5-flash",
            )
        else:
            print(f"[modernize_codebase] Model generation failed: {e}. Falling back to baseline modernization.")
            return _mock_sample_modernization()

    # --- Syntax Guardrail with 1-Step Self-Correction ---
    for field_name in ["modernized_code", "pytest_suite"]:
        code_to_check = getattr(result, field_name)
        is_valid, err_msg, err_line = validate_python_syntax(code_to_check)

        if not is_valid:
            print(f"[AST Guardrail] Detected syntax error in {field_name}: {err_msg}. Triggering self-correction retry.")
            fix_prompt = (
                f"You generated Python code that failed standard library `ast.parse()` validation.\n"
                f"Field: {field_name}\n"
                f"Syntax Error: {err_msg}\n"
                f"Line Number: {err_line}\n\n"
                f"Erroneous Code:\n{code_to_check}\n\n"
                f"Please fix all syntax errors and return ONLY the syntactically valid Python code with no markdown fences."
            )
            try:
                fix_resp = client.models.generate_content(
                    model="gemini-2.5-flash",
                    contents=fix_prompt,
                    config=types.GenerateContentConfig(temperature=0.1),
                )
                fixed_code = re.sub(r"^```(?:python)?\s*", "", fix_resp.text or "", flags=re.MULTILINE)
                fixed_code = re.sub(r"```\s*$", "", fixed_code, flags=re.MULTILINE).strip()

                fix_valid, _, _ = validate_python_syntax(fixed_code)
                if fix_valid:
                    setattr(result, field_name, fixed_code)
                    print(f"[AST Guardrail] Self-correction succeeded for {field_name}.")
            except Exception as fix_err:
                print(f"[AST Guardrail] Self-correction attempt failed: {fix_err}")

    return result

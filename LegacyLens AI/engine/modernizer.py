def calculate_discount(
    amount: Decimal,
    tier: str = "bronze",
    promo_codes: Optional[List[str]] = None,
) -> Decimal:
    """Calculate tier-based and promo-code discounts up to a 40% cap.

    Args:
        amount: Pre-discount subtotal amount.
        tier: Customer loyalty tier (bronze, silver, gold).
        promo_codes: Optional list of applied promotion codes.

    Returns:
        Discounted total as a Decimal.
    """
    clean_promos = list(promo_codes) if promo_codes is not None else []
    rate = Decimal("0.0")
    tier_lower = tier.lower()

    if tier_lower == "bronze":
        if amount > Decimal("100.00"):
            rate = Decimal("0.05")
        elif amount > Decimal("50.00"):
            rate = Decimal("0.02")
    elif tier_lower == "silver":
        if amount > Decimal("500.00"):
            rate = Decimal("0.15")
        elif amount > Decimal("100.00"):
            rate = Decimal("0.10")
        else:
            rate = Decimal("0.05")
    elif tier_lower == "gold":
        if amount > Decimal("1000.00"):
            rate = Decimal("0.25")
        elif amount > Decimal("500.00"):
            rate = Decimal("0.20")
        else:
            rate = Decimal("0.15")

    for promo in clean_promos:
        if promo == "SAVE10":
            rate += Decimal("0.10")
        elif promo == "VIP20":
            rate += Decimal("0.20")

    # Hard cap discount at 40%
    if rate > Decimal("0.40"):
        rate = Decimal("0.40")

    discounted = amount * (Decimal("1.0") - rate)
    return discounted.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def process_order_items(
    items: List[Dict[str, Any]],
    customer_id: str,
    apply_tax: bool = True,
    db_conn: Optional[sqlite3.Connection] = None,
) -> float:
    """Process order line items, apply customer discounts, and calculate taxes.

    Args:
        items: List of item dictionaries with 'price' and 'qty' keys.
        customer_id: Unique customer identifier.
        apply_tax: Whether to calculate state tax and surcharges.
        db_conn: Optional database connection for customer tier lookups.

    Returns:
        Rounded final order amount as a standard float.
    """
    customer = get_customer_record(customer_id, db_conn=db_conn)
    tier = customer.tier if customer.tier in ("bronze", "silver", "gold") else "bronze"

    total_sub = Decimal("0.00")
    for item_dict in items:
        p = Decimal(str(item_dict.get("price", 0)))
        q = int(item_dict.get("qty", 1))
        order_item = OrderItem(item_id=str(item_dict.get("id", "item")), price=p, quantity=q)
        total_sub += order_item.subtotal

    discounted = calculate_discount(total_sub, tier)

    if apply_tax:
        tax_amount = discounted * DEFAULT_TAX_RATE
        surcharge_amount = discounted * SURCHARGE_RATE
        final_total = discounted + tax_amount + surcharge_amount
    else:
        final_total = discounted

    return float(final_total.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


